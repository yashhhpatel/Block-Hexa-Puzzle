FILES = {'en': 'strings_en', 'hi': 'strings_hi', 'es': 'strings_es', 'pt': 'strings_pt',
         'fr': 'strings_fr', 'de': 'strings_de', 'id': 'strings_id', 'ja': 'strings_ja'}


def dart_str(v):
    return '"' + v.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('\n', '\\n') + '"'


for lang, fname in FILES.items():
    path = f'lib/l10n/{fname}.dart'
    s = open(path, encoding='utf-8').read()
    # drop keys that are being replaced or retired
    for key in ['hint_no_coins', 'htp_5_body']:
        s, n = re.subn(r"\n\s*['\"]" + key + r"['\"]:\s*(?:\n\s*)?(?:'(?:[^'\\]|\\.)*'|\"(?:[^\"\\]|\\.)*\"),", '', s)
        assert n == 1, (lang, key, n)
    lines = ''.join(f'  "{k}": {dart_str(v)},\n' for k, v in NEW[lang].items())
    i = s.rindex('};')
    s = s[:i] + '\n  // Hints, achievements\n' + lines + s[i:]
    open(path, 'w', encoding='utf-8').write(s)
print('ok')
